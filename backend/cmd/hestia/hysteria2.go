// runHysteria2Command handles one exact root-helper operation and emits credentials only on an explicit single-profile read.
func runHysteria2Command(mode string, input io.Reader, output io.Writer) int {
	if os.Geteuid() != 0 {
		return 1
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	engine := binding.Installed()
	var err error
	switch mode {
	case "-hysteria2-list":
		if decodeChange(input, 128, &struct{}{}) != nil {
			return 42
		}
		var profiles []panelmodel.Hysteria2Connection
		profiles, err = engine.ListHysteria2()
		if err == nil {
			if profiles == nil {
				profiles = []panelmodel.Hysteria2Connection{}
			}
			var live sync.WaitGroup
			for i := range profiles {
				if len(profiles[i].Underlays) > 0 {
					live.Go(func() { fillHysteriaActive(&profiles[i]) })
				}
			}
			live.Wait()
			err = json.NewEncoder(output).Encode(profiles)
		}
	case "-hysteria2-create", "-hysteria2-update":
		var req panelmodel.Hysteria2Command
		update := mode == "-hysteria2-update"
		if decodeChange(input, 40*1024, &req) != nil || !validHysteria2ID(req.ID) || panelmodel.ValidateHysteria2(req.Hysteria2WriteRequest, update) != nil {
			return 42
		}
		var profile panelmodel.Hysteria2Connection
		profile, err = engine.SaveHysteria2(ctx, req.ID, req.Hysteria2WriteRequest, update)
		if err == nil {
			err = json.NewEncoder(output).Encode(profile)
		}
	case "-hysteria2-read":
		var req panelmodel.AWGIDRequest
		if decodeChange(input, 256, &req) != nil || !validHysteria2ID(req.ID) {
			return 42
		}
		var profile panelmodel.Hysteria2ConnectionProfile
		profile, err = engine.ReadHysteria2Profile(req.ID)
		if err == nil {
			fillHysteriaActive(&profile.Hysteria2Connection)
			err = json.NewEncoder(output).Encode(profile)
		}
	case "-hysteria2-delete":
		var req panelmodel.AWGIDRequest
		if decodeChange(input, 256, &req) != nil || !validHysteria2ID(req.ID) {
			return 42
		}
		err = engine.DeleteHysteria2(ctx, req.ID)
	default:
		return 2
	}
	switch {
	case err == nil:
		return 0
	case errors.Is(err, binding.ErrInvalidOrder), errors.Is(err, binding.ErrInvalidConnector):
		return 42
	case errors.Is(err, binding.ErrNotFound):
		return 44
	case errors.Is(err, binding.ErrConflict):
		return 49
	default:
		return 1
	}
}

// validHysteria2ID accepts only canonical v4 UUIDs generated by the gateway.
func validHysteria2ID(id string) bool {
	u, err := uuid.Parse(id)
	return err == nil && u.Version() == 4 && u.Variant() == uuid.RFC4122 && u.String() == id
}

// fillHysteriaActive reports the live transport only when the selector confirms a member of the persisted list.
func fillHysteriaActive(profile *panelmodel.Hysteria2Connection) {
	if len(profile.Underlays) == 0 {
		return
	}
	if active := controller.Hysteria2ActiveUnderlay(profile.ID); slices.Contains(profile.Underlays, active) {
		profile.ActiveUnderlay = active
	}
}
